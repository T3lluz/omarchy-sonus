"""Virtual Sonar-style channels, built from PipeWire filter-chains.

Each channel is a sink apps can play into, carrying its own 10-band
parametric EQ (a preamp plus chained bq_peaking biquads). Channel outputs are
mixed into EasyEffects when it is running, otherwise into the current
hardware sink.

The graph is a `pipewire -c graph.conf` child in its own session, so it
outlives the engine: a shell restart or plugin reload starts a new engine,
which finds the graph through graph.pid and adopts it. Audio never drops for
a reload. Only turning "Virtual channels" off stops it.
"""

from __future__ import annotations

import os
import shutil
import signal
import subprocess
import threading
import time
from pathlib import Path

from . import eq as eqmod
from .config import CONFIG_DIR, GRAPH_CONF, GRAPH_CONF_PATH, SINK_CHANNELS, SINK_KEYS, load_settings

PID_PATH = CONFIG_DIR / "graph.pid"

HEADER = """# Generated by Sonus. Edits are overwritten when the graph restarts.
context.properties = {
    log.level = 0
}

context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}

context.modules = [
    { name = libpipewire-module-rt
        args = { nice.level = -11 }
        flags = [ ifexists nofail ]
    }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
"""

FOOTER = "]\n"


def _eq_nodes(channel_eq: eqmod.ChannelEq) -> str:
    """The filter graph: preamp -> band0 -> ... -> band9."""
    state = channel_eq.normalized()
    active = state.enabled
    mult = eqmod.db_to_linear(state.preamp) if active else 1.0
    parts = [
        f'                    {{ type = builtin name = {eqmod.PREAMP_NAME} label = linear'
        f' control = {{ "Mult" = {mult:.6f} "Add" = 0.0 }} }}'
    ]
    for index, freq in enumerate(eqmod.BAND_FREQS):
        gain = state.gains[index] if active else 0.0
        parts.append(
            f'                    {{ type = builtin name = {eqmod.band_name(index)} label = bq_peaking'
            f' control = {{ "Freq" = {freq:.1f} "Q" = {eqmod.BAND_Q:.2f} "Gain" = {gain:.2f} }} }}'
        )
    return "\n".join(parts)


def _eq_links() -> str:
    chain = [eqmod.PREAMP_NAME] + [eqmod.band_name(i) for i in range(eqmod.BAND_COUNT)]
    return "\n".join(
        f'                    {{ output = "{a}:Out" input = "{b}:In" }}'
        for a, b in zip(chain, chain[1:])
    )


def _filter_chain(channel, channel_eq: eqmod.ChannelEq) -> str:
    last = eqmod.band_name(eqmod.BAND_COUNT - 1)
    return f"""
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "{channel.description}"
            media.name       = "{channel.description}"
            audio.position   = [ FL FR ]
            filter.graph = {{
                nodes = [
{_eq_nodes(channel_eq)}
                ]
                links = [
{_eq_links()}
                ]
                inputs  = [ "{eqmod.PREAMP_NAME}:In" ]
                outputs = [ "{last}:Out" ]
            }}
            capture.props = {{
                node.name        = "{channel.node_name}"
                node.description = "{channel.description}"
                media.class      = Audio/Sink
                node.virtual     = true
                priority.session = 0
                session.suspend-timeout-seconds = 0
            }}
            playback.props = {{
                node.name    = "output.{channel.node_name}"
                node.passive = true
                node.virtual = true
            }}
        }}
    }}
"""


def render_config(eqs: dict[str, eqmod.ChannelEq] | None = None) -> str:
    if eqs is None:
        eqs = eqmod.load_all(load_settings(), SINK_KEYS)
    body = "".join(
        _filter_chain(channel, eqs.get(channel.key) or eqmod.ChannelEq())
        for channel in SINK_CHANNELS
    )
    return HEADER + body + FOOTER


def write_config(eqs: dict[str, eqmod.ChannelEq] | None = None) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    GRAPH_CONF_PATH.write_text(render_config(eqs), encoding="utf-8")


def _read_pid() -> int | None:
    try:
        return int(PID_PATH.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        return None


def _pid_is_graph(pid: int) -> bool:
    try:
        cmdline = Path(f"/proc/{pid}/cmdline").read_bytes().replace(b"\x00", b" ").decode()
    except OSError:
        return False
    return "pipewire" in cmdline and GRAPH_CONF in cmdline


def _stop_pid(pid: int) -> None:
    try:
        os.kill(pid, signal.SIGTERM)
    except OSError:
        return
    for _ in range(20):
        try:
            os.kill(pid, 0)
        except OSError:
            return
        time.sleep(0.1)
    try:
        os.kill(pid, signal.SIGKILL)
    except OSError:
        pass


def _reap_stale() -> None:
    pid = _read_pid()
    if pid and _pid_is_graph(pid):
        _stop_pid(pid)
    try:
        out = subprocess.run(
            ["pgrep", "-f", f"pipewire -c {GRAPH_CONF}"],
            capture_output=True, text=True, timeout=2.0,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        out = ""
    for item in out.split():
        try:
            extra = int(item)
        except ValueError:
            continue
        if extra != os.getpid() and _pid_is_graph(extra):
            _stop_pid(extra)
    PID_PATH.unlink(missing_ok=True)


def _channels_visible() -> bool:
    try:
        out = subprocess.run(
            ["pactl", "list", "short", "sinks"],
            capture_output=True, text=True, timeout=2.0,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return False
    return all(channel.node_name in out for channel in SINK_CHANNELS)


UNIT = "sonus-graph.service"


def _systemctl(*args: str) -> subprocess.CompletedProcess | None:
    if shutil.which("systemctl") is None:
        return None
    try:
        return subprocess.run(
            ["systemctl", "--user", *args],
            capture_output=True, text=True, timeout=5.0,
        )
    except (OSError, subprocess.SubprocessError):
        return None


def _unit_pid() -> int:
    done = _systemctl("show", "-p", "MainPID", "--value", UNIT)
    try:
        return int(done.stdout.strip()) if done and done.returncode == 0 else 0
    except ValueError:
        return 0


class GraphProcess:
    """Starts, adopts and stops the `pipewire -c` process behind the channels.

    The process runs as a transient user unit, not as a child of the shell:
    restarting omarchy-shell or reloading the plugin must not take the
    channels, and every app playing into them, down with it. Where
    systemd-run is missing it falls back to a detached child.
    """

    def __init__(self) -> None:
        self.error = ""
        self._lock = threading.Lock()

    @staticmethod
    def available() -> bool:
        return shutil.which("pipewire") is not None

    def running(self) -> bool:
        pid = _read_pid()
        return bool(pid) and _pid_is_graph(pid)

    def start(self, eqs: dict[str, eqmod.ChannelEq] | None = None) -> bool:
        with self._lock:
            return self._start(eqs)

    def _launch(self) -> int:
        env_dir = str(CONFIG_DIR)
        if shutil.which("systemd-run"):
            _systemctl("stop", UNIT)
            _systemctl("reset-failed", UNIT)
            try:
                done = subprocess.run(
                    [
                        "systemd-run", "--user", "--quiet", "--collect",
                        f"--unit={UNIT}",
                        "--description=Sonus virtual channels",
                        f"--setenv=PIPEWIRE_CONFIG_DIR={env_dir}",
                        "pipewire", "-c", GRAPH_CONF,
                    ],
                    capture_output=True, text=True, timeout=10.0,
                )
            except (OSError, subprocess.SubprocessError) as exc:
                self.error = str(exc)
                return 0
            if done.returncode == 0:
                for _ in range(30):
                    pid = _unit_pid()
                    if pid:
                        return pid
                    time.sleep(0.05)
            self.error = (done.stderr or "systemd-run failed").strip()
        env = dict(os.environ)
        env["PIPEWIRE_CONFIG_DIR"] = env_dir
        try:
            proc = subprocess.Popen(
                ["pipewire", "-c", GRAPH_CONF],
                env=env,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
        except OSError as exc:
            self.error = str(exc)
            return 0
        return proc.pid

    def _start(self, eqs) -> bool:
        if not self.available():
            self.error = "pipewire not found"
            return False
        write_config(eqs)
        pid = _read_pid()
        if pid and _pid_is_graph(pid) and _channels_visible():
            self.error = ""
            return True
        _reap_stale()
        pid = self._launch()
        if not pid:
            return False
        PID_PATH.write_text(str(pid), encoding="utf-8")
        deadline = time.monotonic() + 4.0
        while time.monotonic() < deadline:
            if not _pid_is_graph(pid):
                self.error = "graph exited immediately"
                return False
            if _channels_visible():
                self.error = ""
                return True
            time.sleep(0.1)
        self.error = ""
        return _pid_is_graph(pid)

    def stop(self) -> None:
        with self._lock:
            if _unit_pid():
                _systemctl("stop", UNIT)
            pid = _read_pid()
            if pid and _pid_is_graph(pid):
                _stop_pid(pid)
            PID_PATH.unlink(missing_ok=True)
